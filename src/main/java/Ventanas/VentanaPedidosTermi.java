private void cargarItemsTerminados() {
        try {
        // Crear modelo de tabla con las columnas
        DefaultTableModel model = new DefaultTableModel();
        model.setColumnIdentifiers(new Object[]{
            "ID Pedido",
            "Categoría",
            "Nombre Producto",
            "Cantidad",
            "Precio Unitario",
            "Subtotal",
            "Estado"
        });

        double totalGeneral=0.0;

        // ✅ Supongamos que tienes una lista de pedidos terminados
        // Si solo recibes un pedido, reemplaza esta lista con Collections.singletonList(pedido);
        List<Pedido> pedidosTerminados = cliente.listarTodosPedidos();

        for (Pedido pedido : pedidosTerminados) {
            for (ItemsPedidos item : pedido.getItems()) {
                if (item.getEstado().equalsIgnoreCase("Terminado")) {
                    model.addRow(new Object[]{
                        pedido.getId(),
                        item.getCategoria(),
                        item.getNombre(),
                        item.getCantidad(),
                        "$" + item.getPrecioUnitario(),
                        "$" + item.getSubtotal(),
                        item.getEstado()
                    });

                    totalGeneral += item.getSubtotal();
                }
            }
        }
        
       TblTerminados.setModel(model);
        TblTerminados.revalidate();
        TblTerminados.repaint();

        DecimalFormat df = new DecimalFormat("#,###.00");
        txtTotal.setText("Total: $" + df.format(totalGeneral));
        } catch (IOException e) {
            JOptionPane.showMessageDialog(this, "Error al cargar los items terminados: " + e.getMessage());
            e.printStackTrace();
        }
    }
    
      
 
  
